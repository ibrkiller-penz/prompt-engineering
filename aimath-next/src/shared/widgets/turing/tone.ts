export function toneLine(s: string): string {
  return Object.prototype.hasOwnProperty.call(TURING_TONE, s) ? TURING_TONE[s] : s;
}

export interface ToneRound {
  q: string;
  a: string;
  b: string;
  machineIs: "A" | "B";
  tell: string;
}

/** 한 판의 화면 문장을 고쳐요. 정답(machineIs)·순서는 그대로예요 */
export function toneRound<T extends ToneRound>(r: T): T {
  return Object.assign({}, r, { q: toneLine(r.q), a: toneLine(r.a), b: toneLine(r.b), tell: toneLine(r.tell) });
}
